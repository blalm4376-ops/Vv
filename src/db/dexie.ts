export class SmartPosErpDB extends Dexie {
  products!: Table<Product, string>;
  warehouses!: Table<Warehouse, string>;
  stockMovements!: Table<StockMovement, string>;
  stockCounts!: Table<StockCount, string>;
  customers!: Table<Customer, string>;
  suppliers!: Table<Supplier, string>;
  sales!: Table<SaleInvoice, string>;
  returns!: Table<ReturnInvoice, string>;
  purchases!: Table<PurchaseInvoice, string>;
  cashboxAccounts!: Table<CashboxAccount, string>;
  cashTransactions!: Table<CashTransaction, string>;
  expenses!: Table<Expense, string>;
  accounts!: Table<AccountNode, string>;
  journalEntries!: Table<JournalEntry, string>;
  employees!: Table<Employee, string>;
  attendance!: Table<AttendanceRecord, string>;
  payroll!: Table<PayrollRecord, string>;
  shifts!: Table<Shift, string>;
  auditLogs!: Table<AuditLog, string>;
  loginAttempts!: Table<LoginAttempt, string>;
  syncQueue!: Table<SyncQueueItem, string>;
  settings!: Table<StoreSettings, string>;

  constructor() {
    super('SmartPosErpDB');
    this.version(1).stores({
      products: 'id, code, sku, barcode, category, status, isDeleted',
      warehouses: 'id, code, isMain',
      stockMovements: 'id, productId, warehouseId, type, referenceId, createdAt',
      stockCounts: 'id, warehouseId, status, createdAt',
      customers: 'id, name, phone, tier',
      suppliers: 'id, name, phone',
      sales: 'id, invoiceNumber, docType, status, customerId, shiftId, idempotencyKey, createdAt',
      returns: 'id, returnNumber, originalInvoiceId, customerId, createdAt',
      purchases: 'id, purchaseNumber, docType, status, supplierId, createdAt',
      cashboxAccounts: 'id, type',
      cashTransactions: 'id, accountId, type, referenceId, createdAt',
      expenses: 'id, category, accountId, date, createdAt',
      accounts: 'id, code, type',
      journalEntries: 'id, entryNumber, referenceId, date, createdAt',
      employees: 'id, role, active',
      attendance: 'id, employeeId, date',
      payroll: 'id, employeeId, month',
      shifts: 'id, cashierId, status, openedAt',
      auditLogs: 'id, actorId, module, createdAt',
      loginAttempts: 'id, identifier, createdAt',
      syncQueue: 'id, entityType, entityId, status, idempotencyKey, createdAt',
      settings: 'id',
    });
  }
}

